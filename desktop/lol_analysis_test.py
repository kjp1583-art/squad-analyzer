    {"게임 번호": "#1", "플레이어": "나", "팀": "블루", "챔피언": "노틸러스", "블루팀 밴": "아리,리신,잭스", "결과": "패배"},
    
    {"게임 번호": "#2", "플레이어": "플레이어J", "팀": "레드", "챔피언": "렐", "블루팀 밴": "야스오,제드,럭스", "결과": "승리"},
