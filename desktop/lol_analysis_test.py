# 파이썬 데이터 분석 도구 가동
df = pd.DataFrame(mock_database)

print("\n" + "="*50)
print("     🤖 내전 데이터 분석 엔진 실시간 브리핑 🤖     ")
print("="*50)

# 1. 플레이어J의 데이터만 쏙 뽑아내기
j_data = df[df["플레이어"] == "플레이어J"]

# 2. 전체 승률 계산
total_games = len(j_data)
total_wins = len(j_data[j_data["결과"] == "승리"])
overall_wr = (total_wins / total_games) * 100

print(f"▶ [플레이어J]의 현재 통계")
print(f"  - 총 전적: {total_games}전 {total_wins}승 {total_games - total_wins}패 (전체 승률: {overall_wr:.0f}%)")

# 3. '렐'이 저격 밴 당했을 때의 데이터 분석
# 플레이어J가 '레드팀'일 때, 상대방인 '블루팀'이 렐을 밴한 판 필터링
banned_games = j_data[j_data["블루팀 밴"].str.contains("렐")]
banned_total = len(banned_games)
banned_wins = len(banned_games[banned_games["결과"] == "승리"])
banned_wr = (banned_wins / banned_total) * 100 if banned_total > 0 else 0

# 4. '렐'이 풀렸을 때 데이터 분석
open_games = j_data[~j_data["블루팀 밴"].str.contains("렐")]
open_total = len(open_games)
open_wins = len(open_games[open_games["결과"] == "승리"])
open_wr = (open_wins / open_total) * 100 if open_total > 0 else 0

print("-"*50)
print(f"📢 [AI 저격 밴 분석 결론]")
print(f"  - 모스트 챔피언 '렐'이 열렸을 때 승률: {open_wr:.0f}%")
print(f"  - 모스트 챔피언 '렐'이 [저격 밴] 되었을 때 승률: {banned_wr:.0f}%")
print("-"*50)

# 승률 차이가 심하면 경고 메시지 출력하기
if open_wr - banned_wr >= 30:
    print("🚨 [🚨특급 경보🚨] 치명적인 약점 포착!")
    print("  => '플레이어J'는 '렐'을 밴하면 승률이 급감하는 '원챔충' 성향이 강합니다.")
    print("  => 다음 판에 이 사람을 만나면 무조건 [ 렐 ] 을 밴카드로 자르십시오!!")
else:
    print("  => 밴 카드에 크게 영향을 받지 않는 올라운더 플레이어입니다.")
print("="*50 + "\n")